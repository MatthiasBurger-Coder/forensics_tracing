package de.burger.forensics.plugin.btmgen.writer;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.time.Clock;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Objects;

/**
 * Writes a single .btm file with a small header and rule blocks.
 */
public final class BtmFileWriter {

    private final Path output;
    private final Clock clock;
    private final boolean includeTimestampHeader;

    /** Preferred constructor keeping time explicit. */
    public BtmFileWriter(Clock clock, Path output) {
        this(clock, output, false);
    }

    /** Preferred constructor keeping time explicit and optional timestamp rendering. */
    public BtmFileWriter(Clock clock, Path output, boolean includeTimestampHeader) {
        this.clock = Objects.requireNonNull(clock, "clock");
        this.output = Objects.requireNonNull(output, "output");
        this.includeTimestampHeader = includeTimestampHeader;
    }

    /** Backward-compatible constructor (uses a system clock). */
    public BtmFileWriter(Path output) {
        this(Clock.systemDefaultZone(), output, false);
    }

    public void write(List<String> rules) {
        write(List.of(), rules);
    }

    public void write(List<String> additionalHeaderLines, List<String> rules) {
        try {
            Files.createDirectories(output.getParent());
            try (var writer = Files.newBufferedWriter(output, StandardCharsets.UTF_8,
                    StandardOpenOption.CREATE, StandardOpenOption.TRUNCATE_EXISTING)) {
                writer.write("# Generated Byteman rules");
                writer.write(System.lineSeparator());
                if (includeTimestampHeader) {
                    writer.write("# Timestamp: " + ZonedDateTime.now(clock).format(DateTimeFormatter.ISO_OFFSET_DATE_TIME));
                    writer.write(System.lineSeparator());
                }
                for (String line : additionalHeaderLines) {
                    writer.write(line);
                    writer.write(System.lineSeparator());
                }
                writer.write(System.lineSeparator());
            }
            appendRules(output, rules);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private void appendRules(Path out, List<String> rules) throws IOException {
        if (rules == null || rules.isEmpty()) return;
        try (var writer = Files.newBufferedWriter(out, StandardCharsets.UTF_8, StandardOpenOption.APPEND)) {
            for (String rule : rules) {
                writer.write(rule);
                writer.write(System.lineSeparator());
                writer.write(System.lineSeparator());
            }
        }
    }
}
